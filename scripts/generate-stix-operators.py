#!/usr/bin/env python3
"""Generate tiny STIX operator fonts with native MATH display variants.

No original font is changed; temporary PUA remapping is deleted on completion.
The E040..E04F range follows the existing E000..E03F parenthesis subset.
Requires fontTools and lv_font_conv 1.5.3. The generator emits raster ink/advance
and variant-specific italic corrections so all geometry uses the painted glyph.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OPERATORS = (0x2211, 0x222B, 0x220F, 0x2210, 0x22C2, 0x22C3, 0x22C0, 0x22C1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--converter", default="lv_font_conv")
    parser.add_argument("--audit-json", type=Path)
    args = parser.parse_args()
    converter = shutil.which(args.converter) or args.converter
    converter_path = Path(converter)
    # WHY: invoking the JS entry point avoids shell quoting and .cmd execution
    # with Unicode/space-containing paths on the supported Windows host.
    if converter_path.suffix.lower() in (".cmd", ".ps1"):
        converter_js = converter_path.parent / "node_modules/lv_font_conv/lv_font_conv.js"
        converter_command = ["node", str(converter_js)]
    else:
        converter_command = [converter]
    source = ROOT / "assets/fonts/STIXTwoMath-Regular.ttf"
    font = TTFont(source)
    font_version = font['name'].getDebugName(5)
    assert font["head"].unitsPerEm == 1000
    math = font["MATH"].table
    variants = dict(zip(math.MathVariants.VertGlyphCoverage.glyphs, math.MathVariants.VertGlyphConstruction))
    italic = math.MathGlyphInfo.MathItalicsCorrectionInfo
    corrections = dict(zip(italic.Coverage.glyphs, (v.Value for v in italic.ItalicsCorrection)))
    names, records = [], []
    for cp in OPERATORS:
        glyph = font.getBestCmap()[cp]
        construction = variants[glyph]
        ladder = construction.MathGlyphVariantRecord
        assert ladder[0].VariantGlyph == glyph, "Base variant must remain index zero"
        assert len(ladder) > 1
        for display, variant in ((False, ladder[0]), (True, ladder[-1])):
            names.append(variant.VariantGlyph)
            records.append({"base_codepoint": cp, "mapped_codepoint": 0xE040 + len(names)-1,
                "display": display, "glyph": variant.VariantGlyph,
                "height_du": variant.AdvanceMeasurement,
                "italic_correction_du": corrections.get(variant.VariantGlyph, 0)})
    for table in font["cmap"].tables:
        if table.isUnicode():
            table.cmap.update({0xE040+i: name for i, name in enumerate(names)})
    all_metrics = {}
    with tempfile.TemporaryDirectory(prefix="numos-stix-operators-") as temp:
        mapped = Path(temp) / "stix-operators.ttf"
        font.save(mapped)
        for size, bpp in ((18, 4), (12, 4), (8, 2)):
            dest = ROOT / f"src/fonts/stix_operators_{size}.c"
            subprocess.run(converter_command + ["--font", str(mapped), "--size", str(size),
                "--bpp", str(bpp), "--format", "lvgl", "--range", "0xE040-0xE04F",
                "--no-compress", "--no-kerning", "-o", str(dest)], check=True)
            text = dest.read_text(encoding="utf-8").replace('#include "lvgl/lvgl.h"', '#include "lvgl.h"')
            text = re.sub(r" \* Opts:.*\n", " * Generated by scripts/generate-stix-operators.py\n", text)
            text = ('/* STIX Two Math; Copyright 2001-2021 The STIX Fonts Project Authors.\n'
                f' * Source: assets/fonts/STIXTwoMath-Regular.ttf; {font_version}.\n'
                f' * Input SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
                ' * License: assets/fonts/LICENSES/STIXTwoMath-OFL-1.1.txt (OFL-1.1).\n */\n') + text
            dest.write_text(text.rstrip()+"\n", encoding="utf-8", newline="\n")
            descriptors = re.findall(r"\.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)", text)
            assert len(descriptors) == len(names) + 1
            all_metrics[size] = [[int(w), int(h), int(x), int(y), (int(adv)+8)//16] for adv,w,h,x,y in descriptors[1:]]
    header = '''// Generated by scripts/generate-stix-operators.py; STIX OFL-1.1.
// Native raster boxes for the actual selected glyph; no guessed MATH-height boxes.
#pragma once
#include <cstdint>
namespace vpam {
struct StixOperatorInk { int16_t width, height, xOffset, yOffset, advance, italicCorrectionDu; };
'''
    for size, metrics in all_metrics.items():
        header += f"inline constexpr StixOperatorInk kStixOperators{size}[] = {{\n"
        for record, metric in zip(records, metrics):
            header += "    {" + ", ".join(map(str, metric + [record["italic_correction_du"]])) + "}, // " + record["glyph"] + "\n"
        header += "};\n"
    header += '''inline constexpr int stixOperatorIndex(uint32_t baseCodepoint) {
    switch (baseCodepoint) {
'''
    for i, cp in enumerate(OPERATORS):
        header += f"        case 0x{cp:X}: return {2*i};\n"
    header += '''        default: return -1;
    }
}
inline const StixOperatorInk* stixOperatorInk(uint32_t baseCodepoint, int16_t em, bool display) {
    const int index = stixOperatorIndex(baseCodepoint);
    if (index < 0) return nullptr;
    const auto* metrics = em >= 15 ? kStixOperators18 : em >= 10 ? kStixOperators12 : kStixOperators8;
    return metrics + index + (display ? 1 : 0);
}
inline constexpr uint32_t stixOperatorCodepoint(uint32_t baseCodepoint, bool display) {
    const int index = stixOperatorIndex(baseCodepoint);
    return index < 0 ? 0 : static_cast<uint32_t>(0xE040 + index + (display ? 1 : 0));
}
} // namespace vpam
'''
    (ROOT / "src/math/font/stix_operator_ink.h").write_text(header, encoding="utf-8", newline="\n")
    audit = {"font_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "generator": "scripts/generate-stix-operators.py", "converter": "lv_font_conv 1.5.3",
        "glyphs": records, "raster_metrics_width_height_offsetX_offsetY_advance": all_metrics,
        "source_file_bytes": {str(size): (ROOT / f"src/fonts/stix_operators_{size}.c").stat().st_size for size in all_metrics}}
    if args.audit_json:
        args.audit_json.parent.mkdir(parents=True, exist_ok=True)
        args.audit_json.write_text(json.dumps(audit, indent=2)+"\n", encoding="utf-8")
    print(json.dumps({k:v for k,v in audit.items() if k not in ("glyphs", "raster_metrics_width_height_offsetX_offsetY_advance")}, indent=2))


if __name__ == "__main__":
    main()
