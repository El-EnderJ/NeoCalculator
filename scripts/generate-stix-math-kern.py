#!/usr/bin/env python3
"""Extract compiled STIX MATH corner kerns; never copies or redistributes fonts.

Usage: python scripts/generate-stix-math-kern.py [--check] [--audit-json PATH]
Requires fontTools. All four corners are required for ordinary after-base scripts:
the base contributes a right corner and the script contributes a left corner.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
CORNERS = ("TopRightMathKern", "TopLeftMathKern", "BottomRightMathKern", "BottomLeftMathKern")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=ROOT / "assets/fonts/STIXTwoMath-Regular.ttf")
    parser.add_argument("--output", type=Path, default=ROOT / "src/math/font/stix_math_kern.h")
    parser.add_argument("--audit-json", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    font = TTFont(args.font)
    font_version = font['name'].getDebugName(5)
    assert font["head"].unitsPerEm == 1000, "NumOS STIX design-unit contract changed"
    cmap = font.getBestCmap()
    compiled = {}
    for size in (18, 12, 8):
        path = ROOT / f"src/fonts/stix_math_{size}.c"
        compiled[size] = set(int(cp, 16) for cp in re.findall(r"/\* U\+([0-9A-Fa-f]+) ", path.read_text(encoding="utf-8")))
        assert compiled[size], f"No compiled glyph inventory parsed from {path}"
    covered = set.intersection(*compiled.values())
    info = font["MATH"].table.MathGlyphInfo.MathKernInfo
    source = dict(zip(info.MathKernCoverage.glyphs, info.MathKernInfoRecords)) if info else {}
    # WHY: table 0 is the implicit zero corner. Deduplicating equal staircases
    # keeps immutable metadata small without allocating anything at runtime.
    tables = [((), (0,))]
    table_ids = {tables[0]: 0}
    records = []
    raw = []
    for cp, glyph in sorted(cmap.items()):
        if cp not in covered or glyph not in source:
            continue
        corner_ids = []
        details = {}
        for corner in CORNERS:
            table = getattr(source[glyph], corner)
            heights = tuple(v.Value for v in table.CorrectionHeight) if table else ()
            kerns = tuple(v.Value for v in table.KernValue) if table else (0,)
            assert len(kerns) == len(heights) + 1
            assert list(heights) == sorted(set(heights)), (glyph, corner, heights)
            assert all(-32768 <= v <= 32767 for v in heights + kerns)
            assert len(heights) <= 255
            key = (heights, kerns)
            # An all-zero table is the implicit-zero table regardless of its heights.
            if not any(kerns):
                key = tables[0]
            if key not in table_ids:
                table_ids[key] = len(tables)
                tables.append(key)
            corner_ids.append(table_ids[key])
            details[corner] = {"heights_du": list(heights), "kerns_du": list(kerns)}
        raw.append({"codepoint": cp, "unicode": f"U+{cp:04X}", "glyph": glyph, "corners": details})
        if any(corner_ids):
            records.append((cp, corner_ids))
    flat = []
    offsets = []
    for heights, kerns in tables:
        offsets.append((len(flat), len(heights)))
        flat.extend(heights + kerns)
    assert len(flat) < 65536 and len(tables) < 65536 and len(records) < 65536
    sha = hashlib.sha256(args.font.read_bytes()).hexdigest()
    header = f'''/*
 * Auto-generated by scripts/generate-stix-math-kern.py; DO NOT EDIT.
 * STIX Two Math {font_version}; UPM=1000.
 * Input SHA-256: {sha}
 * STIX data: Copyright 2001-2021 The STIX Fonts Project Authors; OFL-1.1.
 * NumOS scaffolding: Copyright (C) 2026 Juan Ramon; GPL-3.0-or-later.
 * SPDX-License-Identifier: GPL-3.0-or-later AND OFL-1.1
 * License: assets/fonts/LICENSES/STIXTwoMath-OFL-1.1.txt
 * Sources: OpenType 1.9.1 MATH MathKernInfo / MathKern.
 * Only Unicode glyphs present in all three compiled math fonts are retained.
 */
#pragma once
#include <cstdint>

namespace vpam {{

enum class MathKernCorner : uint8_t {{ TopRight, TopLeft, BottomRight, BottomLeft }};
struct MathKernTableRecord {{ uint16_t offset; uint8_t heightCount; }};
struct MathKernGlyphRecord {{ uint32_t codepoint; uint16_t corner[4]; }};

inline constexpr int16_t kStixMathKernValues[] = {{
'''
    header += "\n".join("    " + ", ".join(str(x) for x in flat[i:i+12]) + "," for i in range(0, len(flat), 12))
    header += "\n};\ninline constexpr MathKernTableRecord kStixMathKernTables[] = {\n"
    header += "\n".join(f"    {{ {offset}, {count} }}," for offset, count in offsets)
    header += "\n};\ninline constexpr MathKernGlyphRecord kStixMathKernGlyphs[] = {\n"
    header += "\n".join(f"    {{ 0x{cp:X}, {{ {', '.join(str(x) for x in ids)} }} }}," for cp, ids in records)
    header += f'''\n}};
inline constexpr uint16_t kStixMathKernGlyphCount = {len(records)};
inline constexpr uint8_t kStixMathKernMaxHeightCount = {max(n for _, n in offsets)};
inline constexpr uint32_t kStixMathKernStorageBytes =
    sizeof(kStixMathKernValues) + sizeof(kStixMathKernTables) + sizeof(kStixMathKernGlyphs);

// WHY: direct immutable flash lookups; no cache, allocation, vtable or recursion.
// Equality selects the interval ABOVE the correction height (OpenType convention).
inline int16_t lookupMathKernDu(uint32_t codepoint, MathKernCorner corner, int32_t heightDu) {{
    const auto cornerIndex = static_cast<uint8_t>(corner);
    if (cornerIndex >= 4) return 0;
    uint16_t lo = 0, hi = kStixMathKernGlyphCount;
    while (lo < hi) {{
        const uint16_t mid = static_cast<uint16_t>(lo + (hi - lo) / 2);
        if (kStixMathKernGlyphs[mid].codepoint < codepoint) lo = mid + 1;
        else hi = mid;
    }}
    if (lo == kStixMathKernGlyphCount || kStixMathKernGlyphs[lo].codepoint != codepoint) return 0;
    const auto& table = kStixMathKernTables[kStixMathKernGlyphs[lo].corner[cornerIndex]];
    uint8_t i = 0;
    while (i < table.heightCount && heightDu >= kStixMathKernValues[table.offset + i]) ++i;
    return kStixMathKernValues[table.offset + table.heightCount + i];
}}

}} // namespace vpam
'''
    if args.check:
        assert args.output.read_text(encoding="utf-8") == header, "Generated MathKern header is stale"
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(header, encoding="utf-8", newline="\n")
    metadata = {
        "input_font_path": "assets/fonts/STIXTwoMath-Regular.ttf", "input_sha256": sha,
        "font_names": {str(n.nameID): n.toUnicode() for n in font["name"].names if n.nameID in (1, 2, 3, 5, 6)},
        "fonttools_version": __import__("fontTools").__version__, "upm": 1000,
        "source_kern_glyph_count": len(source), "compiled_sizes": {str(k): len(v) for k, v in compiled.items()},
        "retained_nonzero_glyphs": len(records), "deduplicated_tables": len(tables),
        "flat_int16_count": len(flat), "max_height_count": max(n for _, n in offsets),
        "table_storage_bytes_expected_4byte_alignment": len(flat)*2 + len(tables)*4 + len(records)*12,
        "source_records_for_compiled_glyphs": raw,
    }
    if args.audit_json:
        args.audit_json.parent.mkdir(parents=True, exist_ok=True)
        args.audit_json.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in metadata.items() if k != "source_records_for_compiled_glyphs"}, indent=2))


if __name__ == "__main__":
    main()
