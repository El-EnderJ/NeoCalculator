"""Inject read-only build identity (commit, dirty flag, env) into NumOS builds.

Writes $BUILD_DIR/numos_generated/numos_build_info.h and adds that directory to
the include path. Only src/BuildInfo.cpp includes the header, so a new commit
or a change of the dirty state recompiles one translation unit, not the whole
firmware (or Giac in the emulator). The header is rewritten only when its
content changes.

Dirty = `git status --porcelain` is not empty when the build starts: tracked
changes or untracked files that are not ignored (both can change what is
compiled). Ignored files (out/, .pio/, ...) do not count.
"""

from __future__ import annotations

import os
import subprocess

Import("env")  # noqa: F821 - supplied by PlatformIO/SCons

PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821


def git_value(*args: str) -> str | None:
    try:
        return subprocess.check_output(
            ["git", *args], cwd=PROJECT_DIR, text=True, encoding="utf-8",
            stderr=subprocess.DEVNULL,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return None


commit = git_value("rev-parse", "HEAD") or "unknown"
short = git_value("rev-parse", "--short=7", "HEAD") or "unknown"
status = git_value("status", "--porcelain")
dirty = bool(status)  # None (no git) counts as clean-but-unknown
environment = env.subst("$PIOENV")  # noqa: F821
build_id = short + ("-dirty" if dirty else "")


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


header = "\n".join([
    "// Generated by scripts/build_metadata.py. Do not edit or commit.",
    "#pragma once",
    f"#define NUMOS_BUILD_COMMIT {c_string(commit)}",
    f"#define NUMOS_BUILD_COMMIT_SHORT {c_string(short)}",
    f"#define NUMOS_BUILD_DIRTY {1 if dirty else 0}",
    f"#define NUMOS_BUILD_ID {c_string(build_id)}",
    f"#define NUMOS_BUILD_ENVIRONMENT {c_string(environment)}",
    "",
])

out_dir = os.path.join(env.subst("$BUILD_DIR"), "numos_generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
out_file = os.path.join(out_dir, "numos_build_info.h")
try:
    with open(out_file, encoding="utf-8") as handle:
        unchanged = handle.read() == header
except OSError:
    unchanged = False
if not unchanged:
    with open(out_file, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(header)

env.Append(CPPPATH=[out_dir])  # noqa: F821
print(f"[build_metadata] numos commit={build_id} env={environment}")
